// ============================================
// if...else Statement
// ============================================

// Variables
let name = "shayon Boidya";
let age = 21;


// ============================================
// if...else
// ============================================

// Check whether the age is greater than 18.
//
// If the condition is true,
// the code inside the if block runs.
//
// Otherwise, the code inside the else block runs.
if (age > 18) {

    // Template literal is used to insert variables
    // inside a string using ${}.
    console.log(`${name} is an adult.`);

} else {

    console.log(`${name} is minor`);
}


// Output:
//
// shayon Boidya is an adult.