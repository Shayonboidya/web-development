// ============================================
// for Loop
// ============================================

// Store the multiplication table number.
let sum = 2;


// A for loop is used to repeat a block of code
// a specific number of times.
//
// Syntax:
//
// for(initialization; condition; update){
//
//      code
//
// }

for (let i = 0; i < 5; i++) {

    // Print the multiplication table.
    console.log(sum + " X " + i + " = " + sum * i);
}


// Output:
//
// 2 X 0 = 0
// 2 X 1 = 2
// 2 X 2 = 4
// 2 X 3 = 6
// 2 X 4 = 8